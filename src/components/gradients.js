/**
 * Zwraca gotowy CSS gradient po nazwie
 * @param {string} name - nazwa gradientu
 * @param {'css'|'cssDiag'} type - kierunek (domyślnie: poziomy)
 */
export function getGradient(name, type = 'css') {
    return gradients[name]?.[type] ?? null;
}

/**
 * Zwraca gradient jako string do background-image
 * gotowy do wklejenia w inline style lub CSS
 */
export function gradientStyle(name, type = 'css') {
    const g = getGradient(name, type);
    return g ? `background-image: ${g};` : '';
}

